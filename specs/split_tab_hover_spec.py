"""Bluelium : diviser deux onglets par glisser-superposer et alléger la barre.

- Glisser un onglet unique (ni groupe, ni sélection multiple, ni vue déjà
  divisée) sur la zone centrale d'un autre onglet compatible (même état
  épinglé, pas déjà en vue divisée) suspend le réordonnancement le temps du
  survol : après 400 ms, la cible se met en évidence aux couleurs du thème
  avec l'icône glyphe_split, et le relâchement forme une vue divisée via
  TabStripModel::AddToNewSplit. Sortir de la zone centrale ou appuyer sur
  Échap restaure le comportement normal sans créer de vue divisée.
- Traite à la fois la bande horizontale classique (DraggingTabsSession + Tab)
  et les onglets verticaux / bande unifiée (DraggedTabsContainer + TabView).
- Préférence booléenne bluelium.split_on_tab_hover (activée par défaut) avec
  interrupteur dans Personnaliser > Barre d'outils.
- Bouton « Diviser » non épinglé par défaut (kPinSplitTabButton = false),
  ré-épinglable dans Personnaliser > Barre d'outils.
"""

