   '      !split_hover_candidate_handle_.Get()) {\n'
   '    ResetSplitHover();\n'
   '    return;\n'
   '  }\n'
   '  TabView* target_view =\n'
   '      views::AsViewClass<TabView>(split_hover_candidate_view_.view());\n'
   '  if (!target_view) {\n'
   '    ResetSplitHover();\n'
   '    return;\n'
   '  }\n'
   '  split_hover_confirmed_ = true;\n'
   '  target_view->SetBlueliumSplitHoverHighlight(true);\n'
   '  split_hover_highlighted_target_view_.SetView(target_view);\n'
   '  if (dragging_views_.size() == 1) {\n'
   '    views::View* dragged_view = dragging_views_.begin()->first.get();\n'
   '    if (dragged_view && dragged_view->layer()) {\n'
   '      dragged_view->layer()->SetOpacity(kBlueliumSplitHoverDraggedOpacity);\n'
   '      split_hover_faded_dragged_view_.SetView(dragged_view);\n'
   '    } else if (TabView* dragged_tab =\n'
   '                   views::AsViewClass<TabView>(dragged_view)) {\n'
   '      dragged_tab->SetBlueliumSplitHoverHighlight(true);\n'
   '      split_hover_highlighted_dragged_view_.SetView(dragged_tab);\n'
   '    }\n'
   '  }\n'
   '}\n'
