   '  if (TabView* dragged = views::AsViewClass<TabView>(\n'
   '          split_hover_highlighted_dragged_view_.view())) {\n'
   '    dragged->SetBlueliumSplitHoverHighlight(false);\n'
   '  }\n'
   '  split_hover_highlighted_dragged_view_.SetView(nullptr);\n'
