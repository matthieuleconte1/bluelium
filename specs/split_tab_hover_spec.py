   'DraggedTabsContainer::SplitHoverZone DraggedTabsContainer::FindSplitHoverHit(\n'
   '    const views::ProposedLayout& layout,\n'
   '    const gfx::Rect& dragged_tab_bounds,\n'
   '    TabView** out_target_view,\n'
   '    tabs::TabHandle* out_target_handle) {\n'
   '  *out_target_view = nullptr;\n'
   '  *out_target_handle = tabs::TabHandle::Null();\n'
   '  TabDragHandler& drag_handler = GetDragHandler();\n'
   '  TabDragController* controller = drag_handler.GetDragController();\n'
   '  TabStripModel* model = drag_handler.GetTabStripModel();\n'
   '  if (!controller || !model) {\n'
   '    return SplitHoverZone::kNone;\n'
   '  }\n'
   '  const int dragged_idx = model->GetIndexOfWebContents(\n'
   '      controller->GetSessionData().source_dragged_contents());\n'
   '  if (dragged_idx == TabStripModel::kNoTab) {\n'
   '    return SplitHoverZone::kNone;\n'
   '  }\n'
   '  const bool dragged_pinned = model->IsTabPinned(dragged_idx);\n'
   '  const std::optional<tab_groups::TabGroupId> focused_group =\n'
   '      model->GetFocusedGroup();\n'
   '\n'
   '  gfx::Rect logical_drag_bounds = dragged_tab_bounds;\n'
   '  if (base::i18n::IsRTL() && IsHorizontalDragSupported()) {\n'
   '    logical_drag_bounds.set_x(\n'
   '        host_view_->GetMirroredXForRect(logical_drag_bounds));\n'
   '  }\n'
   '  const gfx::Point drag_center = logical_drag_bounds.CenterPoint();\n'
   '\n'
   '  for (const auto& child_layout : layout.child_layouts) {\n'
   '    if (!child_layout.visible ||\n'
   '        drag_handler.IsViewDragging(*child_layout.child_view)) {\n'
   '      continue;\n'
   '    }\n'
   '    const TabCollectionNode* child_node =\n'
   '        GetCollectionNodeFromView(*child_layout.child_view);\n'
   '    if (!child_node || child_node->type() != TabCollectionNode::Type::TAB) {\n'
   '      continue;\n'
   '    }\n'
   '    TabView* tab_view = views::AsViewClass<TabView>(child_layout.child_view);\n'
   '    if (!tab_view || tab_view->split()) {\n'
   '      continue;\n'
   '    }\n'
   '    const tabs::TabInterface* target_tab = tab_view->GetTabInterface();\n'
   '    if (!target_tab || target_tab->IsSplit()) {\n'
   '      continue;\n'
   '    }\n'
   '    const int target_idx = model->GetIndexOfTab(target_tab);\n'
   '    if (target_idx == TabStripModel::kNoTab || target_idx == dragged_idx ||\n'
   '        model->IsTabPinned(target_idx) != dragged_pinned ||\n'
   '        model->GetSplitForTab(target_idx).has_value()) {\n'
   '      continue;\n'
   '    }\n'
   '    if (focused_group.has_value() && !dragged_pinned &&\n'
   '        model->GetTabGroupForTab(target_idx) != focused_group) {\n'
   '      continue;\n'
   '    }\n'
   '\n'
   '    const gfx::Rect& b = child_layout.bounds;\n'
   '    const bool target_is_after = target_idx > dragged_idx;\n'
   '    if (drag_axes_ == DragAxes::kVerticalOnly) {\n'
   '      if (b.height() <= 0 || drag_center.y() < b.y() ||\n'
   '          drag_center.y() >= b.bottom()) {\n'
   '        continue;\n'
   '      }\n'
   '      const int margin =\n'
   '          base::ClampRound(b.height() * kBlueliumSplitHoverEdgeMarginRatio);\n'
   '      const int center_top = b.y() + margin;\n'
   '      const int center_bottom = b.bottom() - margin;\n'
   '      if (drag_center.y() >= center_top && drag_center.y() <= center_bottom) {\n'
   '        *out_target_view = tab_view;\n'
   '        *out_target_handle = target_tab->GetHandle();\n'
   '        return SplitHoverZone::kCenter;\n'
   '      }\n'
   '      const bool approaching =\n'
   '          (target_is_after && drag_center.y() < center_top) ||\n'
   '          (!target_is_after && drag_center.y() > center_bottom);\n'
   '      if (approaching) {\n'
   '        *out_target_view = tab_view;\n'
   '        *out_target_handle = target_tab->GetHandle();\n'
   '        return SplitHoverZone::kApproachEdge;\n'
   '      }\n'
   '      return SplitHoverZone::kNone;\n'
   '    } else if (drag_axes_ == DragAxes::kHorizontalOnly) {\n'
   '      if (b.width() <= 0 || drag_center.x() < b.x() ||\n'
   '          drag_center.x() >= b.right()) {\n'
   '        continue;\n'
   '      }\n'
   '      const int margin =\n'
   '          base::ClampRound(b.width() * kBlueliumSplitHoverEdgeMarginRatio);\n'
   '      const int center_left = b.x() + margin;\n'
   '      const int center_right = b.right() - margin;\n'
   '      if (drag_center.x() >= center_left && drag_center.x() <= center_right) {\n'
   '        *out_target_view = tab_view;\n'
   '        *out_target_handle = target_tab->GetHandle();\n'
   '        return SplitHoverZone::kCenter;\n'
   '      }\n'
   '      const bool approaching =\n'
   '          (target_is_after && drag_center.x() < center_left) ||\n'
   '          (!target_is_after && drag_center.x() > center_right);\n'
   '      if (approaching) {\n'
   '        *out_target_view = tab_view;\n'
   '        *out_target_handle = target_tab->GetHandle();\n'
   '        return SplitHoverZone::kApproachEdge;\n'
   '      }\n'
   '      return SplitHoverZone::kNone;\n'
   '    } else {\n'
   '      // Grille 2D (onglets épinglés verticaux).\n'
   '      if (!b.Contains(drag_center)) {\n'
   '        continue;\n'
   '      }\n'
   '      const int mx =\n'
   '          base::ClampRound(b.width() * kBlueliumSplitHoverEdgeMarginRatio);\n'
   '      const int my =\n'
   '          base::ClampRound(b.height() * kBlueliumSplitHoverEdgeMarginRatio);\n'
   '      const gfx::Rect inner(b.x() + mx, b.y() + my,\n'
   '                            std::max(1, b.width() - 2 * mx),\n'
   '                            std::max(1, b.height() - 2 * my));\n'
   '      if (inner.Contains(drag_center)) {\n'
   '        *out_target_view = tab_view;\n'
   '        *out_target_handle = target_tab->GetHandle();\n'
   '        return SplitHoverZone::kCenter;\n'
   '      }\n'
   '      const bool approaching =\n'
   '          (target_is_after && drag_center.x() <= inner.right() &&\n'
   '           drag_center.y() <= inner.bottom()) ||\n'
   '          (!target_is_after && drag_center.x() >= inner.x() &&\n'
   '           drag_center.y() >= inner.y());\n'
   '      if (approaching) {\n'
   '        *out_target_view = tab_view;\n'
   '        *out_target_handle = target_tab->GetHandle();\n'
   '        return SplitHoverZone::kApproachEdge;\n'
   '      }\n'
   '      return SplitHoverZone::kNone;\n'
   '    }\n'
   '  }\n'
   '  return SplitHoverZone::kNone;\n'
